import express from "express";
import path from "path";
import { createServer as createViteServer } from "vite";
import { GoogleGenAI, Type } from "@google/genai";
import dotenv from "dotenv";

dotenv.config();

async function startServer() {
  const app = express();
  const PORT = process.env.PORT ? parseInt(process.env.PORT, 10) : 3000;

  // JSON Body Parser for API Requests
  app.use(express.json());

  // API routes FIRST
  app.get("/api/health", (req, res) => {
    res.json({ status: "ok" });
  });

  // Gemini AI Question Generation Endpoint
  app.post("/api/gemini/generate-questions", async (req, res) => {
    const { topic, textInput, count = 5, language = "id" } = req.body;

    if (!process.env.GEMINI_API_KEY) {
      return res.status(500).json({ error: "GEMINI_API_KEY is not configured on the server." });
    }

    if (!topic && !textInput) {
      return res.status(400).json({ error: "Please provide a topic or text input for question generation." });
    }

    try {
      const ai = new GoogleGenAI({
        apiKey: process.env.GEMINI_API_KEY,
        httpOptions: {
          headers: {
            'User-Agent': 'aistudio-build',
          }
        }
      });

      const prompt = `Generate ${count} high-quality, professional multiple-choice questions for an educational quiz about "${topic || 'given material'}". 
Additional material/context:
"""
${textInput || ''}
"""
Language requirement: the quiz must be generated in ${language === 'id' ? 'Indonesian (Bahasa Indonesia)' : 'English'}.
Make sure the options are realistic but clearly distinguishable back to the correct answer. The options array must contain exactly 4 options. The correctOptionIndex must match the correct option in the array (0-3).`;

      const response = await ai.models.generateContent({
        model: "gemini-3.5-flash",
        contents: prompt,
        config: {
          systemInstruction: "You are an expert educator who writes clear, fair, and pedagogically sound evaluation questions. You always generate a valid JSON array of questions matching the requested schema.",
          responseMimeType: "application/json",
          responseSchema: {
            type: Type.ARRAY,
            items: {
              type: Type.OBJECT,
              properties: {
                text: {
                  type: Type.STRING,
                  description: "The text of the question or prompt."
                },
                options: {
                  type: Type.ARRAY,
                  items: {
                    type: Type.STRING
                  },
                  description: "Array of exactly 4 multiple choice options."
                },
                correctOptionIndex: {
                  type: Type.INTEGER,
                  description: "The correct option index (0, 1, 2, or 3)."
                }
              },
              required: ["text", "options", "correctOptionIndex"]
            }
          }
        }
      });

      const resultText = response.text;
      if (!resultText) {
        throw new Error("No response content generated by Gemini.");
      }

      const questions = JSON.parse(resultText);
      res.json({ success: true, questions });
    } catch (error: any) {
      console.error("Gemini question generation error:", error);
      res.status(500).json({ error: error.message || "Failed to generate questions using Gemini AI." });
    }
  });

  // Vite middleware for development
  if (process.env.NODE_ENV !== "production") {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: "spa",
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.join(process.cwd(), 'dist');
    app.use(express.static(distPath));
    app.get('*', (req, res) => {
      res.sendFile(path.join(distPath, 'index.html'));
    });
  }

  app.listen(PORT, "0.0.0.0", () => {
    console.log(`Server running on http://localhost:${PORT}`);
  });
}

startServer();
